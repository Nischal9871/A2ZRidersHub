/* ---------------------------- Helpers ---------------------------- */
window.PRODUCT_HELPERS = (function () {
  const AVAILABILITY = {
    "in-stock": { label: "Available", cls: "is-available" },
    limited: { label: "Limited Stock", cls: "is-limited" },
    "on-order": { label: "On Order", cls: "is-order" },
    "pre-order": { label: "Pre-Order", cls: "is-order" },
  };

  const byId = (id) => window.PRODUCTS.find((p) => p.id === id);
  const availabilityOf = (p) => AVAILABILITY[p.availability] || AVAILABILITY["in-stock"];

  /* Deterministic grouping: locale-dependent toLocaleString can vary by
     platform ICU build, which would render prices inconsistently. */
  function formatPrice(n) {
    const grouped = String(Math.round(Number(n)))
      .replace(/\B(?=(\d{3})+(?!\d))/g, ",");
    return "NPR " + grouped;
  }

  const featured = () => window.PRODUCTS.filter((p) => p.featured);
  const brands = () => [...new Set(window.PRODUCTS.map((p) => p.brand))].sort();
  const types = () => [...new Set(window.PRODUCTS.map((p) => p.type))].sort();

  function related(p, count) {
    const n = count || 3;
    const sameCat = window.PRODUCTS.filter((x) => x.category === p.category && x.id !== p.id);
    const others = window.PRODUCTS.filter((x) => x.category !== p.category);
    return [...sameCat, ...others].slice(0, n);
  }

  return { AVAILABILITY, byId, availabilityOf, formatPrice, featured, brands, types, related };
})();
